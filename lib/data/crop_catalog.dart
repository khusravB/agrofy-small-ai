  static List<CropProfile> get mainCrops =>
      all.where((crop) => !crop.isCover).toList();

  static List<CropProfile> get coverCrops =>
      all.where((crop) => crop.isCover).toList();

  static CropProfile? byId(String? id) {
    for (final crop in all) {
      if (crop.id == id) {
        return crop;
      }
    }
    return null;
  }

  /// Сопоставляет название культуры из карточки участка со справочником.
  /// «Фрукты» и «Другое» не сопоставляются: севооборот для них не строится
  /// автоматически.
  static CropProfile? fromFieldCrop(String fieldCrop) {
    const mapping = {
      'пшеница': 'wheat',
      'кукуруза': 'maize',
      'хлопок': 'cotton',
      'рис': 'rice',
      'картофель': 'potato',
      'овощи': 'vegetables',
    };

    return byId(mapping[fieldCrop.trim().toLowerCase()]);
  }
